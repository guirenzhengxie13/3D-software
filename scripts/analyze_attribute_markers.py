"""Compare recovered frame marker geometry with both saved marker frameworks.

Nearest-framework distances check internal consistency, not independent
metrology or recovery of undocumented persistent marker identities.
"""

from __future__ import annotations

import argparse
from collections import Counter
import csv
import json
from pathlib import Path

import numpy as np
from scipy.spatial import cKDTree


def statistics(values):
    values = np.asarray(values, float)
    if not len(values):
        return {"observations": 0}
    return {"observations": len(values), "median_mm": float(np.median(values)),
            "p90_mm": float(np.percentile(values, 90)), "p99_mm": float(np.percentile(values, 99)),
            "max_mm": float(values.max()), "within_0_25mm": float(np.mean(values <= .25)),
            "within_1mm": float(np.mean(values <= 1.))}


def process(scan, out):
    index = json.loads((scan / "index.json").read_text(encoding="utf-8"))
    frameworks = {}
    for path in [*sorted(scan.glob("global_markers_*.npz")), scan / "marker_framework.npz"]:
        if path.exists():
            with np.load(path, allow_pickle=False) as arrays:
                xyz = arrays["xyz_scan_mm"].copy()
            if len(xyz):
                frameworks[path.stem] = (xyz, cKDTree(xyz))
    if not frameworks:
        return None
    target = out / index["scan_id"]
    target.mkdir(parents=True, exist_ok=True)
    signs = np.asarray(index.get("optical_to_pose_axes", [1, -1, -1]), float)
    distances = {(stage, name): [] for stage in ("stored", "optimized") for name in frameworks}
    groups = {}
    frame_records = []
    all_world, all_ids, all_stage = [], [], []
    for item in index["frames"]:
        rid = item["id"]
        folder = scan / f"frame_{rid:010d}"
        marker_file = folder / "markers.npz"
        if not marker_file.exists():
            continue
        with np.load(marker_file, allow_pickle=False) as arrays:
            local = arrays["xyz_camera_mm"].copy()
        if not len(local):
            continue
        for stage in ("stored", "optimized"):
            pose_file = folder / f"pose_{stage}.npy"
            if not pose_file.exists():
                continue
            pose = np.load(pose_file, allow_pickle=False)
            world = (local * signs) @ pose[:3, :3].T + pose[:3, 3]
            all_world.append(world)
            all_ids.append(np.full(len(world), rid, np.int64))
            all_stage.append(np.full(len(world), 0 if stage == "stored" else 1, np.uint8))
            for name, (_, tree) in frameworks.items():
                ds, nearest = tree.query(world, workers=1)
                distances[(stage, name)].extend(ds.tolist())
                group_key = (rid >> 32, stage, name)
                groups.setdefault(group_key, []).extend(ds.tolist())
                frame_records.append({"id": rid, "id_high_word": rid >> 32, "stage": stage,
                    "framework": name, **statistics(ds),
                    "nearest_framework_indices_unique": len(set(nearest.tolist())),
                    "note": "Nearest index is a spatial association, not a decoded persistent marker ID."})
    summary = {"scan_id": index["scan_id"], "unit": "mm", "framework_counts": {name: len(values[0]) for name, values in frameworks.items()},
        "stages": [{"pose_stage": stage, "framework": name, **statistics(values)} for (stage, name), values in distances.items()],
        "id_high_word_groups": [{"id_high_word": group, "pose_stage": stage, "framework": name, **statistics(values)} for (group, stage, name), values in sorted(groups.items())],
        "global_record_metadata": index.get("global_marker_records"),
        "limitations": ["Frameworks and poses were generated by the same vendor workflow; distances are internal consistency only.",
            "Nearest-framework associations need not be one-to-one and do not decode original marker IDs.",
            "ID high-word groups are reported without assuming their undocumented capture-state meaning.",
            "Original mkf and database frameworks are kept separately if their bytes differ."]}
    if len(frameworks) >= 2:
        names = list(frameworks)
        source, target_framework = frameworks[names[0]], frameworks[names[-1]]
        summary["framework_to_framework"] = {"first": names[0], "second": names[-1],
            "first_to_second": statistics(target_framework[1].query(source[0])[0]),
            "second_to_first": statistics(source[1].query(target_framework[0])[0])}
    if all_world:
        np.savez_compressed(target / "marker_world_observations.npz", xyz_scan_mm=np.concatenate(all_world),
            frame_ids=np.concatenate(all_ids), stage_code=np.concatenate(all_stage))
    (target / "frames.json").write_text(json.dumps(frame_records, indent=2, allow_nan=False), encoding="utf-8")
    (target / "report.json").write_text(json.dumps(summary, indent=2, allow_nan=False), encoding="utf-8")
    with (target / "frames.csv").open("w", encoding="utf-8", newline="") as stream:
        columns = ["id", "id_high_word", "stage", "framework", "observations", "median_mm", "p90_mm", "max_mm", "within_0_25mm", "within_1mm", "nearest_framework_indices_unique"]
        writer = csv.DictWriter(stream, fieldnames=columns, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(frame_records)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--decoded", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    source, output = args.decoded.resolve(), args.out.resolve()
    if source == output or source in output.parents or output in source.parents:
        parser.error("Keep reports separate from decoded input")
    output.mkdir(parents=True, exist_ok=True)
    results = []
    for path in sorted(source.glob("*/index.json")):
        report = process(path.parent, output)
        if report:
            results.append(report)
            print(json.dumps({"scan": report["scan_id"], "stages": report["stages"]}), flush=True)
    (output / "summary.json").write_text(json.dumps(results, indent=2, allow_nan=False), encoding="utf-8")


if __name__ == "__main__":
    main()
